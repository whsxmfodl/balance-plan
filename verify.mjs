assert.ok(makePlan({...base,modes:['gym'],budget:3,facilityCost:5}).modes.includes('bodyweight'));
assert.ok(makePlan({...base,modes:['gym'],budget:3,facilityCost:3}).modes.includes('gym'));
assert.ok(makePlan({...base,modes:['pilates']}).modes.includes('pilates'),'mat Pilates is available without a facility');
