const now=Date.parse('2026-09-28T00:00:00Z');
const packed=packState({...base,photo:'secret-bytes'},new Set(['2026-09-28']),'2026-09-28',now,new Set(['2026-09-28']));
assert.ok(!packed.includes('secret-bytes'),'photo data is never persisted');
assert.deepEqual(unpackState(packed,now).shortened,['2026-09-28']);
assert.equal(unpackState(packed,now+31*86400000),null);
assert.equal(unpackState('{bad json}',now),null);
assert.equal(unpackState(JSON.stringify({version:2,expires:now+1000,profile:{age:30},startDate:'2026-09-28',completed:[]}),now),null);
