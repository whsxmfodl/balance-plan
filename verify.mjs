assert.ok(!makeSession('running',{...base,walking:'unknown'}).blocks.some(b=>b.detail.includes('달리기 1분')));
assert.ok(!makeSession('running',base,1).blocks.some(b=>b.detail.includes('달리기 1분')),'beginner run intervals are not daily');
assert.ok(!makePlan(base).timeline.match(/\d+~\d+주/),'no fabricated arrival forecast');
assert.match(estimateTimeline({earlier:76,recent:75,weeks:4,target:70,height:170}).title,/20주/);
